test('real Web Audio rendering repeats the chosen count before continuing or ending', async ({ page }) => {
  await page.goto('/');
  const results = await page.evaluate(async () => {
    const { Player } = await import('/src/audio.ts');
    async function render(mode: 'once' | 'loop', count = 1, lastSection = false) {
      const context = new OfflineAudioContext(1, 7 * 48000, 48000);
      Object.defineProperty(context, 'resume', { value: async () => {} });
      const buffer = context.createBuffer(1, 4 * 48000, 48000);
      const data = buffer.getChannelData(0); for (let i = 0; i < data.length; i++) data[i] = (Math.floor(i / 48000) + 1) * 0.2;
      const player = new Player(context as unknown as AudioContext); player.setBuffer(buffer);
      await player.play(lastSection ? 3.5 : 1.5, mode, lastSection ? { start: 3, end: 4 } : { start: 1, end: 2 }, count);
      const output = (await context.startRendering()).getChannelData(0);
      return [0.1, 0.49, 0.51, 1.1, 1.51, 2.1, 2.51, 3.1, 3.6, 4.1, 4.6, 5.1, 5.6, 6.1].map(t => output[Math.round(t * 48000)]);
    }
    return { once: await render('once'), loop: await render('loop'), three: await render('once', 3), ending: await render('once', 3, true) };
  });
  const expected = [0.4, 0.4, 0.4, 0.4, 0.6, 0.6, 0.8, 0.8, 0, 0, 0, 0, 0, 0];
  results.once.forEach((value, i) => expect(value).toBeCloseTo(expected[i], 3));
  results.loop.forEach(value => expect(value).toBeCloseTo(0.4, 3));
  results.three.forEach((value, i) => expect(value).toBeCloseTo([.4, .4, .4, .4, .4, .4, .4, .4, .6, .6, .8, .8, 0, 0][i], 3));
  results.ending.forEach((value, i) => expect(value).toBeCloseTo(i < 8 ? .8 : 0, 3));
});
